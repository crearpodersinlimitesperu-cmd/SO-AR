function escapeHtml(str) {
  return String(str || '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

/**
 * Renderiza el cuerpo íntegro del contrato en HTML limpio compatible con clientes de correo (Gmail/Outlook)
 * y con el sanitizador de mailerDaemon.js.
 */
export function renderContractSectionsHtml(sections = [], accentHex = '#d97706') {
  return sections
    .map((sec) => {
      const artsHtml = (sec.articulos || [])
        .map((art) => {
          const formattedBody = escapeHtml(art.contenido).replace(/\n/g, '<br/>');
          return `
            <div style="margin-bottom: 12px; padding: 10px 12px; background-color: #ffffff; border-left: 3px solid ${accentHex}; border-radius: 4px;">
              <div style="font-size: 13px; font-weight: 700; color: #0f172a; margin-bottom: 4px;">${escapeHtml(art.subtitulo)}</div>
              <div style="font-size: 12.5px; line-height: 1.6; color: #334155;">${formattedBody}</div>
            </div>
          `;
        })
        .join('');

      return `
        <div style="margin-bottom: 16px; background-color: #f8fafc; border: 1px solid #e2e8f0; border-radius: 8px; padding: 14px 16px;">
          <div style="font-size: 11px; font-weight: 800; text-transform: uppercase; color: ${accentHex}; letter-spacing: 0.5px; margin-bottom: 2px;">
            ${escapeHtml(sec.numero)}
          </div>
          <div style="font-size: 14px; font-weight: 800; color: #0f172a; margin-bottom: 10px;">
            ${escapeHtml(sec.titulo)}
          </div>
          ${artsHtml}
        </div>
      `;
    })
    .join('');
}
